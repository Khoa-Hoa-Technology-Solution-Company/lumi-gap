import { useState } from "react";
import { MANUSCRIPT_TEMPLATES, type ManuscriptTemplate } from "@trend/shared-types";
import { useI18n } from "@/i18n";
import { Input } from "@/components/ui/input";

const templates: Record<ManuscriptTemplate, { title: string; description: string; layout: string }> = {
  ARTICLE: { title: "Article template", description: "Single-column article with introduction, related work, methods, results and conclusion.", layout: "article" },
  PROPOSAL: { title: "Proposal template", description: "Research problem, questions, methodology and research plan.", layout: "proposal" },
  REPORT: { title: "Report template", description: "Chapter-based report for a thesis or technical research document.", layout: "report" },
  IEEE_CONFERENCE: { title: "IEEE conference", description: "Two-column IEEEtran conference layout with BibTeX references.", layout: "ieee" },
  PRESENTATION: { title: "Beamer presentation", description: "Research slides with a title page, questions and methods.", layout: "slides" },
  THESIS: { title: "Thesis template", description: "Memoir thesis with chapters, contents and a separate bibliography.", layout: "report" },
  ELSEVIER: { title: "Elsevier article", description: "Elsarticle preprint with front matter, abstract and keywords.", layout: "article" },
  SPRINGER: { title: "Springer proceedings", description: "LNCS research proceedings with abstract, keywords and numbered sections.", layout: "article" },
  APS: { title: "Physics article", description: "REVTeX research paper with a two-column journal layout.", layout: "ieee" },
  BLANK: { title: "Blank document", description: "Minimal LaTeX document. Build your own structure.", layout: "blank" },
};
export function ManuscriptTemplates({ value, onChange }: { value: ManuscriptTemplate; onChange: (template: ManuscriptTemplate) => void }) {
  const { t } = useI18n(), [search, setSearch] = useState("");
  const visible = MANUSCRIPT_TEMPLATES.filter(key => `${t(templates[key].title)} ${t(templates[key].description)}`.toLocaleLowerCase().includes(search.toLocaleLowerCase()));
  return <section className="writing-template-gallery" aria-label={t("Template gallery")}>
    <div className="writing-form-field">
      <label htmlFor="manuscript-template-search">{t("Search templates")}</label>
      <Input id="manuscript-template-search" value={search} onChange={event => setSearch(event.target.value)} placeholder={t("Article, thesis, conference or slides…")} />
    </div>
    <p className="writing-small">{t("Built-in templates. Previews illustrate the layout; your PDF is generated by the selected compiler.")}</p>
    <div className="writing-template-grid" role="radiogroup" aria-label={t("Template")}>
      {visible.map(key => <button key={key} type="button" role="radio" aria-checked={value === key} onClick={() => onChange(key)} className="writing-template-card">
        <span className={`writing-template-paper is-${templates[key].layout}`} aria-hidden="true"><b>{key === "BLANK" ? "" : "Research title"}</b>{key !== "BLANK" ? <><i /><span><i /><i /><i /><i /><i /><i /></span></> : null}</span>
        <strong>{t(templates[key].title)}</strong><small>{t(templates[key].description)}</small>
      </button>)}
    </div>
    {!visible.length ? <p>{t("No matching templates.")}</p> : null}
  </section>;
}
