import { Router } from "express";
import { z } from "zod";
import { validate } from "../../common/middleware/validate.js";
import { createRateLimiter } from "../../common/middleware/rate-limit.js";
import { projectWorkspaceController as c } from "./project-workspace.controller.js";
import * as s from "./dto/project-workspace.schema.js";

export const projectWorkspaceRouter = Router({ mergeParams: true });
const params = validate(s.workspaceParams, "params");
const item = validate(s.workspaceParams.extend({ itemId: z.string().uuid() }), "params");
const page = validate(s.workspacePageSchema.strict(), "query");
const writes = createRateLimiter("projects:workspace-writes", { windowMs: 60 * 60 * 1000, limit: 300, keyGenerator: req => req.user!.sub, standardHeaders: true, legacyHeaders: false });

projectWorkspaceRouter.get("/workspace", params, c.overview);
projectWorkspaceRouter.patch("/workspace/stage", writes, params, validate(s.researchStageSchema), c.stage);
projectWorkspaceRouter.get("/workspace/people", params, validate(s.discussionQuerySchema, "query"), c.people);
projectWorkspaceRouter.get("/workspace/artifacts", params, validate(s.artifactQuerySchema, "query"), c.artifacts);
projectWorkspaceRouter.get("/plan", params, validate(s.planQuerySchema, "query"), c.plan);
projectWorkspaceRouter.put("/plan", writes, params, validate(s.savePlanSchema), c.savePlan);
projectWorkspaceRouter.patch("/plan/draft", writes, params, validate(s.planDraftSchema), c.updatePlanDraft);
projectWorkspaceRouter.get("/plan/revisions", params, page, c.planRevisions);
projectWorkspaceRouter.post("/plan/revisions", writes, params, validate(s.planSnapshotSchema), c.snapshotPlan);
projectWorkspaceRouter.post("/plan/revisions/:itemId/restore", writes, item, validate(s.planRestoreSchema), c.restorePlan);
projectWorkspaceRouter.get("/plan/threads", params, validate(s.planThreadsQuerySchema, "query"), c.planThreads);
projectWorkspaceRouter.post("/plan/threads", writes, params, validate(s.planThreadSchema), c.createPlanThread);
projectWorkspaceRouter.get("/plan/shares", params, c.planShares);
projectWorkspaceRouter.post("/plan/shares", writes, params, validate(s.sharePlanSchema), c.sharePlan);
projectWorkspaceRouter.delete("/plan/shares/:itemId", writes, item, c.revokeShare);
projectWorkspaceRouter.get("/tasks", params, validate(s.taskQuerySchema, "query"), c.tasks);
projectWorkspaceRouter.post("/tasks", writes, params, validate(s.createTaskSchema), c.createTask);
projectWorkspaceRouter.get("/tasks/:itemId", item, page, c.task);
projectWorkspaceRouter.patch("/tasks/:itemId", writes, item, validate(s.updateTaskSchema), c.updateTask);
projectWorkspaceRouter.delete("/tasks/:itemId", writes, item, validate(s.versionSchema), c.deleteTask);
projectWorkspaceRouter.get("/milestones", params, page, c.milestones);
projectWorkspaceRouter.post("/milestones", writes, params, validate(s.milestoneFieldsSchema), c.createMilestone);
projectWorkspaceRouter.patch("/milestones/:itemId", writes, item, validate(s.updateMilestoneSchema), c.updateMilestone);
projectWorkspaceRouter.get("/workspace/comments", params, validate(s.commentQuerySchema, "query"), c.comments);
projectWorkspaceRouter.post("/workspace/comments", writes, params, validate(s.addCommentSchema), c.addComment);
projectWorkspaceRouter.get("/discussions", params, validate(s.discussionQuerySchema, "query"), c.discussions);
projectWorkspaceRouter.post("/discussions", writes, params, validate(s.discussionSchema), c.createDiscussion);
projectWorkspaceRouter.get("/discussions/:itemId", item, page, c.discussion);
projectWorkspaceRouter.patch("/discussions/:itemId", writes, item, validate(s.updateDiscussionSchema), c.updateDiscussion);
projectWorkspaceRouter.post("/discussions/:itemId/messages", writes, item, validate(s.messageSchema), c.reply);
projectWorkspaceRouter.post("/discussions/:itemId/resolve", writes, item, validate(s.resolveDiscussionSchema), c.resolve);
projectWorkspaceRouter.get("/discussions/:itemId/history", item, page, c.discussionHistory);
projectWorkspaceRouter.get("/decisions", params, validate(s.discussionQuerySchema, "query"), c.decisions);
projectWorkspaceRouter.post("/decisions", writes, params, validate(s.decisionSchema), c.createDecision);
projectWorkspaceRouter.patch("/decisions/:itemId", writes, item, validate(s.updateDecisionSchema), c.updateDecision);
projectWorkspaceRouter.get("/decisions/:itemId/history", item, page, c.decisionHistory);
