import { Router } from "express";
import { databaseIdSchema } from "../../common/validation/database-id.js";
import { z } from "zod";
import { validate } from "../../common/middleware/validate.js";
import { createRateLimiter } from "../../common/middleware/rate-limit.js";
import { uploadSinglePdf } from "../../common/middleware/upload.js";
import { workspaceParams } from "./dto/project-workspace.schema.js";
import * as s from "./dto/project-research.schema.js";
import { projectResearchController as c } from "./project-research.controller.js";
export const projectResearchRouter = Router({ mergeParams: true });
const params = validate(workspaceParams, "params"), item = validate(workspaceParams.extend({ itemId: z.string().uuid() }), "params");
const gapParams = validate(workspaceParams.extend({ itemId: databaseIdSchema }), "params");
const writes = createRateLimiter("projects:research-writes", { windowMs: 3600000, limit: 300, keyGenerator: req => req.user!.sub });
const uploads = createRateLimiter("projects:private-source-uploads", { windowMs: 3600000, limit: 20, keyGenerator: req => req.user!.sub });
const synthesisAi = createRateLimiter("projects:research-synthesis-ai", { windowMs: 3600000, limit: 10, keyGenerator: req => req.user!.sub });
projectResearchRouter.get("/synthesis", params, c.synthesis);
projectResearchRouter.get("/discovery", params, c.discovery);
projectResearchRouter.get("/synthesis/history", params, c.synthesisHistory);
projectResearchRouter.put("/synthesis", writes, params, validate(s.saveSynthesisSchema), c.saveSynthesis);
projectResearchRouter.post("/synthesis/generate", synthesisAi, params, validate(s.synthesisSourcesSchema), c.generateSynthesis);
projectResearchRouter.post("/synthesis/accept", writes, params, validate(s.reviewSynthesisSchema), c.acceptSynthesis);
projectResearchRouter.get("/questions", params, c.researchQuestions);
projectResearchRouter.get("/papers", params, validate(s.researchPageSchema, "query"), c.library);
projectResearchRouter.get("/papers/:itemId/analysis", gapParams, c.paperAnalysis);
projectResearchRouter.post("/papers/:itemId/analysis", synthesisAi, gapParams, c.requestPaperAnalysis);
projectResearchRouter.get("/papers/:itemId/suggestions", item, c.suggestions);
projectResearchRouter.post("/papers", writes, params, validate(s.importPaperSchema), c.import);
projectResearchRouter.patch("/papers/:itemId", writes, item, validate(s.organizePaperSchema), c.organize);
projectResearchRouter.post("/papers/:itemId/pdf", uploads, item, uploadSinglePdf, c.upload);
projectResearchRouter.get("/files/:itemId", item, c.file);
projectResearchRouter.patch("/screening", writes, params, validate(s.screeningPolicySchema), c.policy);
projectResearchRouter.post("/screening/:itemId/assign", writes, item, validate(s.assignScreeningSchema), c.assign);
projectResearchRouter.put("/screening/:itemId/vote", writes, item, validate(s.voteScreeningSchema), c.vote);
projectResearchRouter.post("/screening/:itemId/resolve", writes, item, validate(s.resolveScreeningSchema), c.resolve);
projectResearchRouter.get("/screening/:itemId/history", item, c.screeningHistory);
projectResearchRouter.get("/evidence", params, validate(s.researchPageSchema, "query"), c.evidence);
projectResearchRouter.post("/evidence", writes, params, validate(s.createEvidenceSchema), c.createEvidence);
projectResearchRouter.patch("/evidence/:itemId", writes, item, validate(s.editEvidenceSchema), c.editEvidence);
projectResearchRouter.post("/evidence/:itemId/review", writes, item, validate(s.reviewEvidenceSchema), c.reviewEvidence);
projectResearchRouter.get("/evidence/:itemId/history", item, c.evidenceHistory);
projectResearchRouter.get("/gaps/:itemId", gapParams, c.gap);
projectResearchRouter.post("/gaps/:itemId/guidance", writes, gapParams, validate(s.gapGuidanceSchema), c.guidance);
projectResearchRouter.patch("/gaps/:itemId", writes, gapParams, validate(s.reviseGapSchema), c.reviseGap);
projectResearchRouter.post("/gaps/:itemId/assessment", writes, gapParams, validate(s.assessGapSchema), c.assessGap);
projectResearchRouter.post("/gaps/:itemId/evidence", writes, gapParams, validate(s.linkGapEvidenceSchema), c.linkGap);
projectResearchRouter.post("/gaps/:itemId/questions", writes, gapParams, validate(s.deriveQuestionSchema), c.deriveQuestion);
