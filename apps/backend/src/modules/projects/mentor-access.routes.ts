import { Router } from "express";
import { z } from "zod";
import { validate } from "../../common/middleware/validate.js";
import { createRateLimiter } from "../../common/middleware/rate-limit.js";
import { workspaceParams } from "./dto/project-workspace.schema.js";
import * as s from "./dto/mentor-access.schema.js";
import { mentorAccessController as c } from "./mentor-access.controller.js";
export const mentorAccessRouter = Router({ mergeParams: true });
const base = validate(workspaceParams, "params"), access = validate(workspaceParams.extend({ accessId: z.string().uuid() }), "params"), item = validate(workspaceParams.extend({ accessId: z.string().uuid(), itemId: z.string().uuid() }), "params");
const writes = createRateLimiter("projects:mentor-resource-access", { windowMs: 3600000, limit: 200, keyGenerator: r => r.user!.sub });
mentorAccessRouter.use((_r, res, next) => { res.set("Cache-Control", "private, no-store"); next(); });
mentorAccessRouter.get("/", base, validate(s.mentorAccessPageSchema, "query"), c.workspace);
mentorAccessRouter.get("/catalog", base, validate(s.mentorAccessPageSchema, "query"), c.catalog);
mentorAccessRouter.get("/tasks", base, validate(s.mentorAccessPageSchema, "query"), c.tasks);
mentorAccessRouter.get("/papers/:paperId/shares", validate(workspaceParams.extend({ paperId: z.string().uuid() }), "params"), validate(s.mentorAccessPageSchema, "query"), c.paperShares);
mentorAccessRouter.put("/:accessId", writes, access, validate(s.configureMentorAccessSchema), c.configure);
mentorAccessRouter.post("/:accessId/revoke", writes, access, validate(s.mentorAccessActionSchema), c.revoke);
mentorAccessRouter.post("/:accessId/shares", writes, access, validate(s.mentorResourceWriteSchema), c.share);
mentorAccessRouter.get("/:accessId/shares/:itemId/pdf", item, c.paperPdf);
mentorAccessRouter.get("/:accessId/shares/:itemId", item, c.resource);
mentorAccessRouter.post("/:accessId/shares/:itemId/revoke", writes, item, validate(s.mentorAccessActionSchema), c.unshare);
mentorAccessRouter.get("/:accessId/feedback", access, validate(s.mentorFeedbackPageSchema, "query"), c.feedback);
mentorAccessRouter.post("/:accessId/feedback", writes, access, validate(s.mentorFeedbackSchema), c.comment);
mentorAccessRouter.put("/:accessId/feedback/:itemId", writes, item, validate(s.mentorFeedbackStatusSchema), c.handle);
mentorAccessRouter.get("/:accessId/history", access, validate(s.mentorAccessPageSchema, "query"), c.history);
mentorAccessRouter.get("/:accessId/agreements", access, validate(s.mentorAccessPageSchema, "query"), c.agreements);
mentorAccessRouter.post("/:accessId/agreements", writes, access, validate(s.mentorAgreementSchema), c.propose);
mentorAccessRouter.post("/:accessId/agreements/:itemId/respond", writes, item, validate(s.mentorAgreementResponseSchema), c.respond);
