import { Router } from "express";
import { z } from "zod";
import { validate } from "../../common/middleware/validate.js";
import { createRateLimiter } from "../../common/middleware/rate-limit.js";
import { workspaceParams } from "./dto/project-workspace.schema.js";
import * as s from "./dto/project-contributions.schema.js";
import { projectContributionsController as c } from "./project-contributions.controller.js";
import { contributionEvaluationController as e } from "./contribution-evaluation.controller.js";
import * as es from "./dto/contribution-evaluation.schema.js";
export const projectContributionsRouter = Router({ mergeParams: true });
const params = validate(workspaceParams, "params"), item = validate(workspaceParams.extend({ itemId: z.string().uuid() }), "params");
const writes = createRateLimiter("projects:contribution-writes", { windowMs: 3600000, limit: 150, keyGenerator: req => req.user!.sub });
projectContributionsRouter.get("/evaluation/rules", params, e.rules);
projectContributionsRouter.get("/evaluation/writing-suggestions", params, validate(es.writingSuggestionsSchema, "query"), e.writingSuggestions);
projectContributionsRouter.post("/evaluation/rules", writes, params, validate(es.evaluationRuleSchema), e.createRule);
projectContributionsRouter.get("/evaluation/board", params, validate(es.evaluationBoardSchema, "query"), e.board);
projectContributionsRouter.post("/evaluation/outcomes", writes, params, validate(es.evaluationProposalSchema), e.propose);
projectContributionsRouter.get("/evaluation/outcomes/:itemId", item, e.detail);
projectContributionsRouter.post("/evaluation/outcomes/:itemId/decisions", writes, item, validate(es.evaluationDecisionSchema), e.decide);
projectContributionsRouter.post("/evaluation/runs", writes, params, validate(es.evaluationRunSchema), e.requestRun);
projectContributionsRouter.get("/evaluation/runs/:itemId", item, e.run);
projectContributionsRouter.get("/evaluation/snapshots", params, validate(es.evaluationBoardSchema, "query"), e.snapshots);
projectContributionsRouter.get("/evaluation/snapshots/:itemId", item, e.snapshot);
projectContributionsRouter.get("/activity", params, validate(s.activitySchema, "query"), c.activity);
projectContributionsRouter.get("/work", params, validate(s.contributionsPageSchema, "query"), c.list);
projectContributionsRouter.post("/work", writes, params, validate(s.createWorkContributionSchema), c.create);
projectContributionsRouter.get("/work/:itemId", item, c.detail);
projectContributionsRouter.patch("/work/:itemId", writes, item, validate(s.editWorkContributionSchema), c.edit);
projectContributionsRouter.post("/work/:itemId/submit", writes, item, validate(s.contributionVersionSchema), c.submitWork);
projectContributionsRouter.post("/work/:itemId/reviews", writes, item, validate(s.contributionReviewSchema), c.review);
projectContributionsRouter.get("/periods", params, c.periods);
projectContributionsRouter.post("/periods", writes, params, validate(s.allocationPeriodSchema), c.createPeriod);
projectContributionsRouter.get("/periods/:itemId", item, c.period);
projectContributionsRouter.get("/periods/:itemId/history", item, c.history);
projectContributionsRouter.post("/periods/:itemId/revisions", writes, item, validate(s.allocationDraftSchema), c.draft);
projectContributionsRouter.post("/periods/:itemId/challenges", writes, item, validate(s.allocationChallengeSchema), c.challenge);
projectContributionsRouter.get("/revisions/:itemId", item, c.revision);
projectContributionsRouter.patch("/revisions/:itemId", writes, item, validate(s.allocationEditSchema), c.editDraft);
projectContributionsRouter.post("/revisions/:itemId/submit", writes, item, validate(s.contributionVersionSchema), c.submitDraft);
projectContributionsRouter.post("/revisions/:itemId/decisions", writes, item, validate(s.allocationDecisionSchema), c.decide);
projectContributionsRouter.get("/revisions/:itemId/export", item, c.export);
projectContributionsRouter.get("/my-history", params, c.myHistory);
projectContributionsRouter.get("/my-history/export", writes, params, c.exportMyHistory);
projectContributionsRouter.get("/advisor-contributions", params, c.advisorContributions);
